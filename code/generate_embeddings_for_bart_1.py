import paths

import pandas as pd

data = pd.read_csv(paths.MERGED)

from sentence_transformers import SentenceTransformer
from tqdm.auto import tqdm


def get_embeddings(df, text_cols, model_name="mixedbread-ai/deepset-mxbai-embed-de-large-v1"):
    print(f"Loading Model: {model_name}...")
    model = SentenceTransformer(model_name)
    prefix = "passage: " if 'e5' in model_name else ""
    df_out = df.copy()

    for col in tqdm(text_cols, desc="Embedding Columns"):
        texts = [f"{prefix}{t}" for t in df[col].fillna("").astype(str).tolist()]
        embeddings = model.encode(texts, show_progress_bar=False, batch_size=32)
        df_out[f"{col}_embedding"] = list(embeddings)

    return df_out

target_to_text_map = {
    'conf': 'text_confidence',
    'cmpcy': 'text_complacency',
    'const': 'text_constraints',
    'calc': 'text_calculation',
    'colr': 'text_coll_resp',
    'compli': 'text_compliance',
    'consp': 'text_conspiracy'
}

# Ensure we only process targets that exist in the dataframe
target_to_text_map = {k: v for k, v in target_to_text_map.items() if k in data.columns and v in data.columns}

data = get_embeddings(data, list(target_to_text_map.values()))

import numpy as np
def expand_embeddings_before_saving(df, text_cols):
    df_out = df.copy()
    for col in text_cols:
        emb_dim = len(df_out[f"{col}_embedding"].iloc[0])
        emb_matrix = np.stack(df_out[f"{col}_embedding"].values)
        emb_df = pd.DataFrame(
            emb_matrix,
            columns=[f"{col}_emb_{i}" for i in range(emb_dim)],
            index=df_out.index
        )
        df_out = pd.concat([df_out, emb_df], axis=1)
        df_out.drop(columns=[f"{col}_embedding"], inplace=True)
    return df_out

data_expanded = expand_embeddings_before_saving(data, list(target_to_text_map.values()))

print(data.text_coll_resp_embedding)

