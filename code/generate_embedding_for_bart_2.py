import numpy as np
def expand_embeddings_before_saving(df, text_cols):
    """
    Original expansion function – expects columns named '{col}_embedding'
    and creates '{col}_emb_i' columns.
    """
    df_out = df.copy()
    for col in text_cols:
        emb_col = f"{col}_embedding"
        if emb_col not in df_out.columns:
            print(f"Warning: '{emb_col}' not found. Skipping {col}.")
            continue

        emb_dim = len(df_out[emb_col].iloc[0])
        emb_matrix = np.stack(df_out[emb_col].values)
        emb_df = pd.DataFrame(
            emb_matrix,
            columns=[f"{col}_emb_{i}" for i in range(emb_dim)],
            index=df_out.index
        )
        df_out = pd.concat([df_out, emb_df], axis=1)
        df_out.drop(columns=[emb_col], inplace=True)

    return df_out

# Expand using the base column names
data_expanded = expand_embeddings_before_saving(data, base_cols)

